#!/usr/bin/env python3
"""Focused EC406 real Ed25519 signatures bound to EC405 genuine RFC3161 fixtures.

Only the immediate EC405.audit call is mocked in this *new child fixture*;
its return was generated by the actual EC405 crypto suite with genuine local
WARC/RFC3161 sources.  Older EC404 and deeper ancestry are already synthetic
and mocked in their own fixtures.  No real independent custodian is claimed.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from pathlib import Path
import unittest
from unittest.mock import patch

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from ec295_delivery_anchor import anchor as errors
from ec350_tsa_timestamp import timestamp as tsa
from ec405_warc_time import test_protocol as pfixture
from . import protocol as core
from . import operator


class OriginalCrossWitnessTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        pfixture.GenuineWarcTimestampTests.setUpClass()

    @classmethod
    def tearDownClass(cls):
        pfixture.GenuineWarcTimestampTests.tearDownClass()

    def setUp(self):
        self.f=pfixture.GenuineWarcTimestampTests(
            'test_01_real_warc_11_three_http_bytes_and_two_genuine_signed_timestamps')
        self.f.setUp()
        self.parent_report=self.f.calibrate()
        self.extra=dict(self.f.extra)
        self.extra[core.NEW_SCALARS[11]]=(datetime.now(timezone.utc)+
            timedelta(minutes=10)).strftime('%Y-%m-%dT%H:%M:%SZ')
        self.extra[core.REPEAT_NAMES[0]]=['f'*64]
        self.extra[core.REPEAT_NAMES[1]]=[0]
        self.roster={'schema':core.ROSTER_SCHEMA,
            'claimed_directory_lineage_id':self.f.f.lineage,'assignments':[]}
        self.bundle={'schema':core.BUNDLE_SCHEMA,
            'claimed_directory_lineage_id':self.f.f.lineage,
            'parent_ec405_original_warc_timestamp_bundle_original':{
                'path':self.f.extra[core.parent.NEW_SCALARS[0]],
                'sha256':self.f.extra[core.parent.NEW_SCALARS[1]]},
            'outside_custody_witness_roster_original':None,
            'epochs':[{'epoch_index':0,'publishers':[]}]}
        self.keys={}
        self.claims={}
        self.witnesses={}
        for letter in ('A','B'):
            self.add_role(letter)
        self.save_roster()
        self.save_bundle()
        self.anchor_first()

    def tearDown(self):
        self.f.tearDown()

    def archive(self,doc,name):
        return self.f.archive(doc,'ec406-'+name)

    def role(self,letter):
        return self.bundle['epochs'][0]['publishers'][0 if letter=='A' else 1]

    def add_role(self,letter):
        idx=0 if letter=='A' else 1
        role='Publisher'+letter
        self.keys[letter]={}
        keys={}
        for keytype in ('custodian','witness'):
            sk=Ed25519PrivateKey.generate()
            raw=sk.public_key().public_bytes(serialization.Encoding.Raw,
                                             serialization.PublicFormat.Raw)
            keyref=self.archive(raw,keytype+'-public-'+letter)
            keys[keytype]=sk
            self.extra[core.NEW_SCALARS[(3 if keytype=='custodian' else 5)+idx]]=keyref['sha256']
        self.keys[letter]=keys
        aid='TestCustodian'+letter
        wid='TestWitness'+letter
        pubrefs=[]
        # public refs are separately anchored in the external roster.
        for kind in ('custodian','witness'):
            raw=keys[kind].public_key().public_bytes(serialization.Encoding.Raw,
                                                      serialization.PublicFormat.Raw)
            pubrefs.append(self.archive(raw,'roster-'+kind+'-'+letter))
        self.roster['assignments'].append({
            'publisher_id':role,'custodian_id':aid,'witness_id':wid,
            'custodian_public_key_original':pubrefs[0],
            'witness_public_key_original':pubrefs[1]})
        token=self.f.role(letter)['rfc3161_original']
        warc=self.f.role(letter)['warc_original']
        root=tsa._certificate(Path(self.f.data[letter]['root']).read_bytes())
        genuine=core.parent._verified_tsa_token(Path(token['path']).read_bytes(),
                  Path(warc['path']).read_bytes(),root,pfixture.POLICY)
        gen=core.stamp(genuine['token_gen_time'])
        witness_stamp=core.stamp(genuine['token_gen_time']+timedelta(seconds=10))
        receipt=self.f.f.role(letter)['signed_archive_receipt_original']
        accession_claim={
            'schema':core.ACCESSION_CLAIM_SCHEMA,'directory_lineage_id':self.f.f.lineage,
            'publisher_id':role,'custodian_id':aid,'epoch_index':0,'sequence':1,
            'previous_accession_sha256':None,'archive_record_id':'TestAccession'+letter,
            'original_ec404_signed_capture_receipt_sha256':receipt['sha256'],
            'original_warc_sha256':warc['sha256'],'original_rfc3161_sha256':token['sha256'],
            'verified_token_gen_time_utc':gen,'claimed_accession_utc':gen}
        self.claims[letter]=accession_claim
        self.bundle['epochs'][0]['publishers'].append({
            'publisher_id':role,'custodian_id':aid,'witness_id':wid,
            'signed_accession_original':None,'signed_cross_witness_original':None})
        aref=self.resign_accession(letter)
        witness_claim={
            'schema':core.WITNESS_CLAIM_SCHEMA,'directory_lineage_id':self.f.f.lineage,
            'publisher_id':role,'witness_id':wid,'epoch_index':0,'sequence':1,
            'previous_witness_sha256':None,'witness_event_id':'TestWitnessEvent'+letter,
            'signed_accession_original_sha256':aref['sha256'],
            'original_warc_sha256':warc['sha256'],'original_rfc3161_sha256':token['sha256'],
            'claimed_witness_utc':witness_stamp}
        self.witnesses[letter]=witness_claim
        self.resign_witness(letter)

    def resign_accession(self,letter,*,corrupt_sig=False):
        claim=self.claims[letter]
        sig=self.keys[letter]['custodian'].sign(core.ACCESSION_DOMAIN+core.canonical(claim)).hex()
        if corrupt_sig:sig=('0' if sig[0]!='0' else '1')+sig[1:]
        aref=self.archive({'schema':core.ACCESSION_SCHEMA,'claim':claim,
                           'signature_hex':sig},'signed-accession-'+letter)
        self.role(letter)['signed_accession_original']=aref
        return aref

    def resign_witness(self,letter,*,corrupt_sig=False):
        claim=self.witnesses[letter]
        sig=self.keys[letter]['witness'].sign(core.WITNESS_DOMAIN+core.canonical(claim)).hex()
        if corrupt_sig:sig=('0' if sig[0]!='0' else '1')+sig[1:]
        wref=self.archive({'schema':core.WITNESS_SCHEMA,'claim':claim,
                           'signature_hex':sig},'signed-witness-'+letter)
        self.role(letter)['signed_cross_witness_original']=wref
        return wref

    def save_roster(self):
        r=self.archive(self.roster,'custody-external-roster')
        self.bundle['outside_custody_witness_roster_original']=r
        self.extra[core.NEW_SCALARS[2]]=r['sha256']

    def save_bundle(self):
        b=self.archive(self.bundle,'custody-original-bundle')
        self.extra[core.NEW_SCALARS[0]]=b['path']
        self.extra[core.NEW_SCALARS[1]]=b['sha256']

    def anchor_first(self):
        for letter in ('A','B'):
            idx=0 if letter=='A' else 1
            self.extra[core.NEW_SCALARS[7+idx]]=self.role(letter)[
                'signed_accession_original']['sha256']
            self.extra[core.NEW_SCALARS[9+idx]]=self.role(letter)[
                'signed_cross_witness_original']['sha256']

    def refresh(self,*,roster=False,anchor=True):
        if roster:self.save_roster()
        self.save_bundle()
        if anchor:self.anchor_first()

    def evaluate(self,derive=True):
        opts=dict(self.extra)
        if derive:opts.pop(core.AUDIT_ONLY[0],None)
        with patch.object(core,'_inputs',return_value={}),\
             patch.object(core.parent,'audit',return_value=self.parent_report):
            return core.derive_inventory(**opts) if derive else core.audit(**opts)

    def calibrate(self):
        result=self.evaluate()
        self.extra[core.REPEAT_NAMES[0]]=[result['custody_witness_epoch_reviews'][0][
            'custody_witness_epoch_inventory_sha256']]
        self.extra[core.REPEAT_NAMES[1]]=[2]
        result=self.evaluate()
        self.extra[core.AUDIT_ONLY[0]]=result[
            'receiver_verified_custody_witness_inventory_sha256']
        return self.evaluate(False)

    def denied(self,contains=None):
        with self.assertRaises(errors.AnchorError) as err:self.evaluate()
        if contains:self.assertIn(contains,err.exception.code)

    def test_01_genuine_dual_signatures_and_original_token_sha(self):
        out=self.calibrate()
        self.assertEqual(out['exit_code'],2)
        self.assertTrue(out['bounded_local_custody_witness_and_real_ec405_parent_consistency'])
        self.assertEqual(out['verified_joint_custody_witness_and_real_parent_publishers'],2)
        self.assertEqual(out['custody_witness_epoch_reviews'][0]['verified_signed_witness_count'],2)
        self.assertTrue(all(out[k] is False for k in core.NEGATIVES))

    def test_02_derive_never_returns_signed_evidence_or_pass(self):
        out=self.evaluate()
        self.assertEqual(out['schema'],core.DERIVE_SCHEMA)
        self.assertEqual(out['exit_code'],2)
        self.assertEqual(len(out['unsigned_custody_witness_evidence_inventory']['epochs'][0]['publishers']),2)
        self.calibrate()
        self.assertNotIn('unsigned_custody_witness_evidence_inventory',self.evaluate(False))

    def test_03_accession_signature_forgery_denied(self):
        self.resign_accession('A',corrupt_sig=True)
        self.refresh()
        self.denied('ACCESSION_SIGNATURE_INVALID')

    def test_04_witness_signature_forgery_denied(self):
        self.resign_witness('B',corrupt_sig=True)
        self.refresh()
        self.denied('WITNESS_SIGNATURE_INVALID')

    def test_05_signed_warc_sha_mismatch_denied(self):
        self.claims['A']['original_warc_sha256']='a'*64
        self.resign_accession('A')
        self.refresh()
        self.denied('SIGNED_ACCESSION_REAL_ORIGINAL')

    def test_06_signed_accession_sha_witness_link_denied(self):
        self.claims['A']['claimed_accession_utc']=core.stamp(
            core.utc(self.claims['A']['claimed_accession_utc'])+timedelta(seconds=1))
        self.resign_accession('A')
        self.refresh()
        self.denied('SIGNED_WITNESS_EXACT_ACCESSION')

    def test_07_cross_witness_cannot_be_same_public_key_as_custodian(self):
        entry=self.roster['assignments'][0]
        entry['witness_public_key_original']=entry['custodian_public_key_original']
        self.extra[core.NEW_SCALARS[5]]=entry['witness_public_key_original']['sha256']
        self.refresh(roster=True)
        self.denied('KEY_PATH_OR_EXTERNAL_PIN_INVALID')

    def test_08_same_original_path_for_both_publishers_denied(self):
        self.role('B')['signed_accession_original']=self.role('A')['signed_accession_original']
        self.refresh()
        self.denied('PATH_REUSED')

    def test_09_duplicate_record_id_even_if_signed_denied(self):
        self.claims['B']['archive_record_id']=self.claims['A']['archive_record_id']
        self.resign_accession('B')
        self.refresh()
        self.denied('RECORD_ID')

    def test_10_claimed_witness_time_before_genuine_rfc3161_token_unresolved(self):
        self.witnesses['A']['claimed_witness_utc']='2020-01-01T00:00:00Z'
        self.resign_witness('A')
        self.refresh()
        result=self.evaluate()
        self.assertTrue(result[core.FLAGS[3]])
        self.assertEqual(result['exit_code'],2)
        self.assertEqual(result['verified_joint_custody_witness_and_real_parent_publishers'],1)

    def test_11_witness_missing_first_is_denied(self):
        self.role('A')['signed_cross_witness_original']=None
        self.refresh(anchor=False)
        self.denied('FIRST_TWO_SIGNED')

    def test_12_original_external_sha_mismatch_is_not_renewed_by_derivation(self):
        self.extra[core.NEW_SCALARS[7]]='e'*64
        self.save_bundle()
        result=self.evaluate()
        self.assertTrue(result[core.FLAGS[1]])
        self.assertEqual(result['exit_code'],2)

    def test_13_wrong_parent_real_inventory_is_unavailable(self):
        self.parent_report=dict(self.parent_report)
        self.parent_report['receiver_verified_warc_timestamp_inventory_sha256']='0'*64
        self.denied('UNCHANGED_REAL_EC405_PARENT_REPORT_INVALID')

    def test_14_parent_joint_coverage_never_upgraded(self):
        self.parent_report=dict(self.parent_report)
        rows=[dict(x) for x in self.parent_report['warc_timestamp_epoch_reviews']]
        rows[0]['joint_warc_timestamp_and_real_parent_count']=0
        self.parent_report['warc_timestamp_epoch_reviews']=rows
        self.parent_report['verified_joint_warc_timestamp_and_real_parent_publishers']=0
        self.parent_report['bounded_local_warc_timestamp_and_real_ec404_parent_consistency']=False
        self.parent_report[core.parent.FLAGS[5]]=True
        self.parent_report['status']=core.parent.OUTCOMES[5]+'_unresolved'
        out=self.evaluate()
        self.assertTrue(out[core.FLAGS[0]])
        self.assertEqual(out['verified_joint_custody_witness_and_real_parent_publishers'],0)

    def test_15_external_roster_key_path_alias_denied(self):
        self.roster['assignments'][0]['custodian_public_key_original']={
            'path':self.extra[core.parent.NEW_SCALARS[0]],
            'sha256':self.extra[core.parent.NEW_SCALARS[1]]}
        self.extra[core.NEW_SCALARS[3]]=self.extra[core.parent.NEW_SCALARS[1]]
        self.refresh(roster=True)
        self.denied('KEY_PATH_OR_EXTERNAL_PIN_INVALID')

    def test_16_missing_bundle_ref_denied_without_signer_or_network(self):
        self.bundle['parent_ec405_original_warc_timestamp_bundle_original']['sha256']='a'*64
        self.refresh()
        self.denied('REAL_EC405_LINK')

    def test_17_invalid_accession_record_id_denied(self):
        self.claims['A']['archive_record_id']='bad id with whitespace'
        self.resign_accession('A')
        self.refresh()
        self.denied('RECORD_ID')

    def test_18_denial_output_is_not_pass_or_data_leak(self):
        doc=operator.denial('audit-historical-ec339-custody-witness',
            errors.AnchorError('EC406_TEST_DENIED','permission_denied'))
        self.assertEqual(doc['exit_code'],3)
        self.assertTrue(all(doc[k] is False for k in core.NEGATIVES))

if __name__=='__main__':
    unittest.main()
